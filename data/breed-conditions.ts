const ALL_PROFILES = [...DOG_PROFILES, ...CAT_PROFILES];

function normalizeBreedKey(raca: string): string {
  return raca
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9 -]/g, '')
    .trim();
}

/**
 * Busca o perfil de saúde da raça com matching tolerante.
 * Retorna o perfil SRD/Vira-lata como fallback se não achar.
 */
export function getBreedHealthProfile(
  raca: string,
  tipo: 'cachorro' | 'gato' | 'outro',
): BreedHealthProfile | null {
  if (tipo === 'outro') return null;
  const species: 'dog' | 'cat' = tipo === 'gato' ? 'cat' : 'dog';
  const key = normalizeBreedKey(raca);

  if (!key) {
    return ALL_PROFILES.find(
      (p) => p.species === species && (p.breedKey === 'viralata' || p.breedKey === 'srd'),
    ) ?? null;
  }

  // Match exato
  const exact = ALL_PROFILES.find((p) => p.species === species && p.breedKey === key);
  if (exact) return exact;

  // Match por contém (ex: "Labrador Retriever Chocolate" → "labrador retriever")
  const partial = ALL_PROFILES.find(
    (p) => p.species === species && (key.includes(p.breedKey) || p.breedKey.includes(key)),
  );
  if (partial) return partial;

  // Fuzzy: cobre typos antigos salvos no MMKV antes da feature de canonicalização
  const speciesPool = ALL_PROFILES.filter((p) => p.species === species);
  const fuzzy = bestMatch(key, speciesPool.map((p) => p.breedKey), 55);
  if (fuzzy) {
    return speciesPool.find((p) => p.breedKey === fuzzy.value) ?? null;
  }

  // Fallback pra SRD/vira-lata
  return ALL_PROFILES.find(
    (p) => p.species === species && (p.breedKey === 'viralata' || p.breedKey === 'srd'),
  ) ?? null;
}

