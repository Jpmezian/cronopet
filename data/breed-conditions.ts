// ─── Tipos públicos ────────────────────────────────────────────────────

export type ConditionCategory =
  | 'orthopedic'         // displasia, problemas articulares
  | 'cardiac'            // cardiopatia mitral, cardiomiopatia
  | 'respiratory'        // braquicefalia, colapso traqueal
  | 'dermatological'     // alergias, dermatite atópica
  | 'gastrointestinal'   // sensibilidade alimentar, GDV
  | 'ophthalmological'   // catarata, atrofia de retina
  | 'endocrine'          // hipotireoidismo, diabetes, Addison
  | 'neurological'       // epilepsia, doença do disco
  | 'urinary'            // urolitíase, doença renal
  | 'oncological';       // predisposição a cânceres específicos

/** Severidade clínica + frequência observada na raça */
export type ConditionSeverity = 'monitor' | 'common' | 'serious';

export interface Predisposition {
  /** Nome em pt-BR pra mostrar pro tutor */
  condition: string;
  category: ConditionCategory;
  severity: ConditionSeverity;
  /** Sintomas observáveis pelo tutor — usado pra cruzar com MedicalEvents */
  watchFor: MedicalEventType[];
  /** Idade típica em que começa a aparecer (anos) */
  ageOnsetYears?: number;
  /** Texto curto sobre o que é, em linguagem leiga */
  brief: string;
}

export interface BreedHealthProfile {
  /** Chave normalizada (lowercase, sem acento) — usada no lookup */
  breedKey: string;
  /** Nome canônico pra exibição */
  displayName: string;
  species: 'dog' | 'cat';
  /** Predisposições conhecidas */
  predispositions: Predisposition[];
  /** Minutos de exercício recomendados por dia (0 = não aplicável) */
  exerciseMinPerDay: number;
  /** Frequência de banho em dias (0 = sob demanda apenas) */
  bathFrequencyDays: number;
  /** Necessidade de tosa/escovação */
  groomingNeeds: 'low' | 'medium' | 'high';
  /** Faixa de peso saudável adulto (kg) */
  weightRange: { min: number; max: number };
  /** Expectativa de vida (anos) */
  lifeExpectancyYears: { min: number; max: number };
  /** Tolerância ao calor — `low` = braquicefálico ou pelagem dupla */
  heatTolerance: 'low' | 'medium' | 'high';
  coldTolerance: 'low' | 'medium' | 'high';
  /** Risco de obesidade — labrador/beagle/cavalier alto */
  obesityRisk: 'low' | 'medium' | 'high';
  /** Frase curta resumindo o cuidado mais importante */
  ownerNote: string;
}

