/**
 * Extrai pistas de necessidade racial pra alimentar `recommendFoods` em
 * `data/foods.ts`. Cada flag bate com um boost no scoring de rações.
 */
export function getBreedFoodHints(profile: BreedHealthProfile | null) {
  if (!profile) return undefined;
  const conditions = profile.predispositions.map((p) => p.condition.toLowerCase());
  return {
    sensitiveSkin: conditions.some(
      (c) => c.includes('atóp') || c.includes('alergia') || c.includes('dobra') || c.includes('demodec'),
    ),
    sensitiveStomach: conditions.some(
      (c) => c.includes('pancreat') || c.includes('intestinal') || c.includes('inflamatór') || c.includes('amiloid') || c.includes('insuficiência pancr'),
    ),
    obesityProne: profile.obesityRisk === 'high',
    lowFatNeeded: conditions.some(
      (c) => c.includes('pancreat') || c.includes('hipertriglicer'),
    ),
    urinaryCare: conditions.some(
      (c) => c.includes('urolit') || c.includes('urinár') || c.includes('renal') || c.includes('flutd') || c.includes('cistinúria'),
    ),
  };
}
